import { McpAgent } from "agents/mcp";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { addBudgetToLead, addNoteToLead, addTagToLead, closeLead, getLead, moveLead, pauseLeadAgent } from "./tools/leads";
import { updateContactField } from "./tools/contacts";
import { canUseTool } from "./utils/canUseTools";

export class MyMCP extends McpAgent {
	server = new McpServer({
		name: "Kommo MCP",
		version: "1.0.0",
	});

	private getConfig() {
		return (this as any).props;
	}

	async init() {

		const kommoCLient = this.getConfig();

		/*──────────────── move_lead ────────────────*/
		if (canUseTool(kommoCLient, "move_lead")) {
			this.server.tool(
				"move_lead",
				"This tool is useful when you need to move a lead to a different pipeline.",
				{
					lead_id: z
						.number()
						.describe("Unique ID assigned by Kommo CRM to the lead. This identifier is used to fetch all related information for a specific lead within the system."),
					pipeline_id: z
						.number()
						.describe("ID of the pipeline where the lead should be moved."),
					status_id: z
						.number()
						.describe("ID of the stage within the target pipeline where the lead should be placed.")
				},
				async ({ lead_id, pipeline_id, status_id }) => {
					try {
						const lead = await getLead(lead_id, kommoCLient);

						if (lead === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to move lead: the specified lead does not exist in Kommo or could not be retrieved."
									}
								]
							}
						}

						const res = await moveLead(lead_id, pipeline_id, status_id, kommoCLient);

						if (res === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to move lead: Kommo API rejected the update request. Please verify the pipeline_id and status_id are valid."
									}
								]
							}
						}

						return {
							content: [
								{
									type: "text",
									text: "Lead successfully moved to the specified pipeline and status."
								}
							]
						}

					} catch (error) {
						console.error("💥 [move_lead] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: `Error al mover el lead: ${(error as Error).message || String(error)}`
								}
							]
						}
					}
				}
			);
		}

		/*──────────────── pause_agent ──────────────*/
		if (canUseTool(kommoCLient, "pause_agent")) {
			this.server.tool(
				"pause_agent",
				"This tool pauses the assigned agent for a specific lead.",
				{
					lead_id: z
						.number()
						.describe("Unique ID assigned by Kommo CRM to the lead. This identifier is used to fetch all related information for a specific lead within the system."),
					switch_field_id: z
						.number()
						.describe("ID of the switch field to pause for this lead."),
					switch_field_value: z
						.boolean()
						.describe("Status of the switch field to pause for this lead.")
				},
				async ({ lead_id, switch_field_id, switch_field_value = false }) => {
					try {
						const lead = await getLead(lead_id, kommoCLient);

						if (lead === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to pause agent: the specified lead does not exist in Kommo or could not be retrieved."
									}
								]
							}
						}

						const res = await pauseLeadAgent(lead_id, switch_field_id, switch_field_value, kommoCLient);

						if (res === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to pause agent: Kommo API rejected the update request. Please verify the switch_field_id is valid."
									}
								]
							}
						}

						return {
							content: [
								{
									type: "text",
									text: "Agent successfully paused for the specified lead."
								}
							]
						}

					} catch (error) {
						console.error("💥 [pause_agent] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: `Error al pausar el agente: ${(error as Error).message || String(error)}`
								}
							]
						}
					}
				}
			);
		}

		/*──────────────── add_note ──────────────*/
		if (canUseTool(kommoCLient, "add_note")) {
			this.server.tool(
				"add_note",
				"This tool adds a note to a specific lead in Kommo, storing contextual or summarized information directly in the lead’s activity history.",
				{
					lead_id: z
						.number()
						.describe("Unique ID assigned by Kommo CRM to the lead. This identifier is used to fetch all related information for a specific lead within the system."),
					note: z
						.string()
						.describe("A concise note generated by the agent based on the full conversation, summarizing the key points, user intent, and any relevant context to be stored in the lead’s history.")
				},
				async ({ lead_id, note }) => {
					try {
						const lead = await getLead(lead_id, kommoCLient);

						if (lead === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to add note: the specified lead does not exist in Kommo or could not be retrieved."
									}
								]
							}
						}

						const res = await addNoteToLead(lead_id, kommoCLient, note);

						if (res === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to add note: Kommo API rejected the request. Please verify the lead_id is valid and the note content is acceptable."
									}
								]
							}
						}

						return {
							content: [
								{
									type: "text",
									text: "Note added successfully."
								}
							]
						}

					} catch (error) {
						console.error("💥 [add_note] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: `Error al añadir nota al lead: ${(error as Error).message || String(error)}`
								}
							]
						}
					}
				}
			)
		}

		/*──────────────── request_human ──────────────*/
		if (canUseTool(kommoCLient, "request_human")) {
			this.server.tool(
				"request_human",
				"Escalates a lead to a human agent in a single call. Moves the lead to the specified pipeline/status, pauses the AI agent via the switch field, and adds a summary note. Operations run best-effort: if one fails, the others still execute and the response reports the outcome of each step.",
				{
					lead_id: z
						.number()
						.describe("Unique ID assigned by Kommo CRM to the lead. This identifier is used to fetch all related information for a specific lead within the system."),
					pipeline_id: z
						.number()
						.describe("ID of the pipeline where the lead should be moved when escalating to a human."),
					status_id: z
						.number()
						.describe("ID of the stage within the target pipeline where the lead should be placed."),
					switch_field_id: z
						.number()
						.describe("ID of the switch field that controls the AI agent pause state for this lead."),
					switch_field_value: z
						.boolean()
						.describe("Value to set on the switch field (typically false to pause the AI agent)."),
					note: z
						.string()
						.describe("Summary note explaining why the lead is being escalated to a human, stored in the lead's activity history.")
				},
				async ({ lead_id, pipeline_id, status_id, switch_field_id, switch_field_value, note }) => {
					try {
						const lead = await getLead(lead_id, kommoCLient);

						if (lead === null) {
							return {
								content: [
									{
										type: "text",
										text: JSON.stringify({
											status: "failed",
											lead_id,
											error: "lead_not_found",
											message: "The specified lead does not exist in Kommo or could not be retrieved."
										})
									}
								]
							}
						}

						const moveRes = await moveLead(lead_id, pipeline_id, status_id, kommoCLient);
						const pauseRes = await pauseLeadAgent(lead_id, switch_field_id, switch_field_value, kommoCLient);
						const noteRes = await addNoteToLead(lead_id, kommoCLient, note);

						const steps = {
							move_lead: moveRes !== null,
							pause_agent: pauseRes !== null,
							add_note: noteRes !== null
						};

						const allOk = steps.move_lead && steps.pause_agent && steps.add_note;
						const failed_steps: { step: string; hint: string }[] = [];

						if (!steps.move_lead) failed_steps.push({ step: "move_lead", hint: "verify pipeline_id and status_id" });
						if (!steps.pause_agent) failed_steps.push({ step: "pause_agent", hint: "verify switch_field_id" });
						if (!steps.add_note) failed_steps.push({ step: "add_note", hint: "verify note content" });

						return {
							content: [
								{
									type: "text",
									text: JSON.stringify({
										status: allOk ? "success" : "partial",
										lead_id,
										steps,
										failed_steps,
										message: allOk
											? "Human handoff completed."
											: "Human handoff partially completed."
									})
								}
							]
						}

					} catch (error) {
						console.error("💥 [request_human] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: JSON.stringify({
										status: "error",
										lead_id,
										error: "unexpected_error",
										message: (error as Error).message || String(error)
									})
								}
							]
						}
					}
				}
			);
		}

		/*──────────────── close_lead ──────────────*/
		if (canUseTool(kommoCLient, "close_lead")) {
			this.server.tool(
				"close_lead",
				"Closes a lead as lost in a single call. Sets the lead to the system 'lost' status (143) with the given loss reason and adds a detailed note explaining why it was closed. Operations run best-effort: if one fails, the other still executes and the response reports the outcome of each step.",
				{
					lead_id: z
						.number()
						.describe("Unique ID assigned by Kommo CRM to the lead."),
					loss_reason_id: z
						.number()
						.describe("ID of the loss reason to assign when closing the lead as lost. Must be a valid loss_reason_id from the Kommo account."),
					note: z
						.string()
						.describe("Detailed note explaining why the lead is being closed/lost, stored in the lead's activity history.")
				},
				async ({ lead_id, loss_reason_id, note }) => {
					try {
						const lead = await getLead(lead_id, kommoCLient);

						if (lead === null) {
							return {
								content: [
									{
										type: "text",
										text: JSON.stringify({
											status: "failed",
											lead_id,
											error: "lead_not_found",
											message: "The specified lead does not exist in Kommo or could not be retrieved."
										})
									}
								]
							}
						}

						const closeRes = await closeLead(lead_id, loss_reason_id, kommoCLient);
						const noteRes = await addNoteToLead(lead_id, kommoCLient, note);

						const steps = {
							close_lead: closeRes !== null,
							add_note: noteRes !== null
						};

						const allOk = steps.close_lead && steps.add_note;
						const failed_steps: { step: string; hint: string }[] = [];

						if (!steps.close_lead) failed_steps.push({ step: "close_lead", hint: "verify loss_reason_id is valid" });
						if (!steps.add_note) failed_steps.push({ step: "add_note", hint: "verify note content" });

						return {
							content: [
								{
									type: "text",
									text: JSON.stringify({
										status: allOk ? "success" : "partial",
										lead_id,
										steps,
										failed_steps,
										message: allOk
											? "Lead closed as lost."
											: "Lead close partially completed."
									})
								}
							]
						}

					} catch (error) {
						console.error("💥 [close_lead] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: JSON.stringify({
										status: "error",
										lead_id,
										error: "unexpected_error",
										message: (error as Error).message || String(error)
									})
								}
							]
						}
					}
				}
			);
		}

		/*──────────────── add_tag ──────────────*/
		if (canUseTool(kommoCLient, "add_tag")) {
			this.server.tool(
				"add_tag",
				"This tool adds a tag to a specific lead in Kommo.",
				{
					lead_id: z
						.number()
						.describe("Unique ID assigned by Kommo CRM to the lead. This identifier is used to fetch all related information for a specific lead within the system."),
					tag_id: z
						.number()
						.describe("ID of the tag to add to the lead."),
				},
				async ({ lead_id, tag_id }) => {
					try {
						const lead = await getLead(lead_id, kommoCLient);

						if (lead === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to add tag: the specified lead does not exist in Kommo or could not be retrieved."
									}
								]
							}
						}

						const res = await addTagToLead(lead_id, tag_id, kommoCLient);

						if (res === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to add tag: Kommo API rejected the request. Please verify the tag_id is valid and exists in your Kommo account."
									}
								]
							}
						}

						return {
							content: [
								{
									type: "text",
									text: "Tag added successfully."
								}
							]
						}
					} catch (error) {
						console.error("💥 [add_tag] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: `Error al añadir tag al lead: ${(error as Error).message || String(error)}`
								}
							]
						}
					}
				}
			);
		}

		/*──────────────── add_budget ──────────────*/
		if (canUseTool(kommoCLient, "add_budget")) {
			this.server.tool(
				"add_budget",
				"This tool adds a budget to a specific lead in Kommo.",
				{
					lead_id: z
						.number()
						.describe("Unique ID assigned by Kommo CRM to the lead. This identifier is used to fetch all related information for a specific lead within the system."),
					budget_field_value: z
						.number()
						.describe("Budget to add to this lead.")
				},
				async ({ lead_id, budget_field_value }) => {
					try {
						const lead = await getLead(lead_id, kommoCLient);

						if (lead === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to add budget: the specified lead does not exist in Kommo or could not be retrieved."
									}
								]
							}
						}

						const res = await addBudgetToLead(lead_id, budget_field_value, kommoCLient);

						if (res === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to add budget: Kommo API rejected the request. Please verify the lead_id is valid and the budget value is a valid number."
									}
								]
							}
						}

						return {
							content: [
								{
									type: "text",
									text: "Budget successfully added to the specified lead."
								}
							]
						}

					} catch (error) {
						console.error("💥 [add_budget] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: `Error al agregar el presupuesto al lead: ${(error as Error).message || String(error)}`
								}
							]
						}
					}
				}
			);
		}

		/*──────────────── update_contact_field ──────────────*/
		if (canUseTool(kommoCLient, "update_contact_field")) {
			this.server.tool(
				"update_contact_field",
				"This tool updates a custom enum/select field on a contact in Kommo.",
				{
					contact_id: z
						.number()
						.describe("ID del contacto en Kommo CRM."),
					field_id: z
						.number()
						.describe("ID del campo custom a actualizar."),
					enum_id: z
						.number()
						.describe("ID del valor enum a setear en el campo.")
				},
				async ({ contact_id, field_id, enum_id }) => {
					try {
						const res = await updateContactField(contact_id, field_id, enum_id, kommoCLient);

						if (res === null) {
							return {
								content: [
									{
										type: "text",
										text: "Failed to update contact field: Kommo API rejected the request. Please verify the contact_id, field_id, and enum_id are valid."
									}
								]
							}
						}

						return {
							content: [
								{
									type: "text",
									text: "Contact field updated successfully."
								}
							]
						}

					} catch (error) {
						console.error("💥 [update_contact_field] Error:", error);
						return {
							content: [
								{
									type: "text",
									text: `Error al actualizar el campo del contacto: ${(error as Error).message || String(error)}`
								}
							]
						}
					}
				}
			);
		}

	}
}